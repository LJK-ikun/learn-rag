# -*- coding: utf-8 -*-
"""
这个文件干什么：整个项目的**配置中心**。

把所有"会变的东西"集中到这一个文件里 —— 语料在哪、用哪个 embedding 模型、
切多大、检索取几条。别的模块一律 `from config import XXX`，绝不自己散着写死。

【为什么值得单独一个文件】
RAG 系统里最容易踩的坑是"同一个参数两个地方写得不一样"。最要命的就是
embedding 模型名：建索引时用 A 模型，查询时用 B 模型 —— 维度相同的话
**不报错，静默返回垃圾结果**。所以模型名和维度必须绑在一起、只在这里定义。

【一条容易忽略的规矩】
`load_dotenv` 一定要传**显式路径**。不传的话它靠调用栈去猜当前文件在哪，
一旦代码不是从文件跑起来的（比如管道、REPL），就会扔一个
`AssertionError: frame.f_back is not None` 出来。这个坑我们已经踩过一次了。
"""
from __future__ import annotations

import os
from pathlib import Path

from dotenv import load_dotenv

# ============================================================
# 0. 项目根目录 + 加载 .env
# ============================================================
ROOT = Path(__file__).resolve().parent
# ↑ __file__ 是本文件路径，resolve() 把相对路径/软链接解析成绝对路径，
#   再取 .parent 拿到所在目录。这样无论从哪个目录运行脚本，路径都对。

load_dotenv(ROOT / ".env")
# ↑ 显式路径，不用默认的 find_dotenv()（那玩意靠调用栈猜，会崩）。


# ============================================================
# 1. 读环境变量的两个小工具
# ============================================================
def env(name: str, default: str = "") -> str:
    """读一个环境变量并去掉首尾空白。没配就返回默认值。"""
    return (os.environ.get(name) or default).strip()
    # ↑ os.environ.get 在变量不存在时返回 None，再 or default 兜住 None。
    #   最后 strip()：.env 里手写很容易多敲空格，
    #   而 key 尾部多个空格会导致 401，报错信息还看不出原因，非常坑。


def require(name: str) -> str:
    """读一个**必须存在**的环境变量。缺了就直接报一句人话，而不是让 401 在后面炸。"""
    value = env(name)
    if not value:
        raise SystemExit(
            f"\n[配置缺失] 环境变量 {name} 没有配置。\n"
            f"  请打开 {ROOT / '.env'} 填上，或参考 {ROOT / '.env.example'}。\n"
        )
    return value


# ============================================================
# 2. 语料位置
# ============================================================
INTERVIEW_DIR = Path(env("INTERVIEW_DIR", r"D:\Project\my_code\interview"))
# ↑ 面试笔记在**另一个仓库**里（my_code），这里直接指过去。
#   为什么不复制一份过来：复制就意味着两份真相 —— 以后笔记改了，
#   索引用的还是旧的那份，而且不会有任何报错。指路径则永远同步。
#   想换语料不用改代码，改 .env 里的 INTERVIEW_DIR 就行。


# ============================================================
# 3. 向量化（Embedding）配置
# ============================================================
EMBEDDING_API_KEY = env("DASHSCOPE_API_KEY")   # 不在导入时 require，见文件末尾说明
EMBEDDING_BASE_URL = env("DASHSCOPE_BASE_URL", "https://dashscope.aliyuncs.com/compatible-mode/v1")
EMBEDDING_MODEL = env("EMBEDDING_MODEL", "text-embedding-v4")

_dim = env("EMBEDDING_DIM")
EMBEDDING_DIM: int | None = int(_dim) if _dim else None
# ↑ 留空 = 用模型自己的默认维度（text-embedding-v4 是 1024）。
#   填 512 就走"降维"——存储省一半，质量掉多少要实验才知道。
#   注意：维度是索引的**物理形状**，改了就必须重建索引，没有别的选择。


# ============================================================
# 4. 对话（Chat）配置
# ============================================================
CHAT_API_KEY = env("DEEPSEEK_API_KEY")
CHAT_BASE_URL = env("CHAT_BASE_URL", "https://api.deepseek.com")
CHAT_MODEL = env("CHAT_MODEL", "deepseek-v4-flash")
# ↑ 注意这里和上面是**两家不同的服务**：向量化走阿里、对话走 DeepSeek。
#   这不是将就，是常态 —— DeepSeek 压根没有 /embeddings 接口。
#   embedding 和 chat 本来就是两个独立能力，各挑各的最优即可。


# ============================================================
# 5. 切分参数
# ============================================================
MAX_CHARS = 800
# ↑ 一个 chunk 最多多少字。超了就二次切。
#   参考：中文大致 1 字 ≈ 1~1.5 token，800 字 ≈ 600~1000 token。
#   你笔记里 2.1 节的建议是 256~512 token，我们取偏大值，
#   因为面试笔记里一段就是一整块论述，切太碎反而把论证打断。

MIN_CHARS = 120
# ↑ 一个 chunk 至少多少字。比这还短的相邻块会**合并**。
#   为什么：像 "### 4.6 RAGAS（顺带提，评估那篇会展开）" 这种小节，
#   正文可能就一行字。单独成块的话向量会被这一行字"稀释"，
#   而且这种块几乎跟任何问题都不够像，纯属占位噪声。


# ============================================================
# 6. 检索参数
# ============================================================
TOP_K = 5
# ↑ 一次检索取几条。取太少可能漏，取太多会往 prompt 里塞噪声。

FETCH_K = 20
# ↑ 精排/融合**之前**先捞多少条候选。M5 的混合检索会用：
#   向量检索捞 20 条、BM25 捞 20 条，融合完再砍到 TOP_K。
#   这就是"召回宽、精排窄"两阶段的基本形状。


# ============================================================
# 7. 索引落盘位置
# ============================================================
INDEX_DIR = ROOT / "index"
# ↑ M5 换成 Chroma 之后，向量和元数据落在这个目录。
#   已在 .gitignore 里排掉 —— 索引是**派生产物**，能重建，不该入库。


# ============================================================
# 8. 自检
# ============================================================
def describe() -> str:
    """把当前配置打出来，用于排查"我到底连的是哪个模型"。"""
    lines = [
        "当前配置",
        f"  语料目录    : {INTERVIEW_DIR}",
        f"  向量模型    : {EMBEDDING_MODEL}  维度={EMBEDDING_DIM or '模型默认'}",
        f"  向量服务    : {EMBEDDING_BASE_URL}",
        f"  对话模型    : {CHAT_MODEL}",
        f"  对话服务    : {CHAT_BASE_URL}",
        f"  切片        : 每块最多 {MAX_CHARS} 字，不足 {MIN_CHARS} 字合并",
        f"  检索        : 召回 {FETCH_K} 条 → 取前 {TOP_K} 条",
    ]
    return "\n".join(lines)


# 注意：这里**没有**在任何地方 require("DASHSCOPE_API_KEY")。
# 因为 config.py 会被 chunker.py 这种"纯计算、不联网"的模块 import，
# 而纯计算部分不该因为"没配 key"就跑不起来 —— 那会让测试无法离线跑。
# 所以 key 的检查推迟到真正要发请求的那一刻（embedder.py 里做）。
# 这是"纯计算和要联网的分开放"那条规矩的具体落实。
